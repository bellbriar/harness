#!/usr/bin/env python3
"""Write docs/RULES.md, the rules reference (A6): every rule in the
rulebook, with what a finding from it means, what it cites, and, for the
rules that run, why it matters and how to fix it, with examples.

    python tools/make_rules_reference.py           # rewrite docs/RULES.md
    python tools/make_rules_reference.py --check   # exit 1 if it is stale

It reads src/bellbriar_harness/rulebook.json and guidance.py and nothing
else, so its output is the same on every machine; tests/test_part_r3.py
fails when docs/RULES.md is not what this script writes.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from bellbriar_harness.bundle import rulebook_digest  # noqa: E402
from bellbriar_harness.engine import load_rulebook  # noqa: E402
from bellbriar_harness.guidance import guidance_for  # noqa: E402

OUT = ROOT / "docs" / "RULES.md"

#: What a finding from a rule of each verdict basis means.
BASIS = {
    "sc": "a FAIL is a failure of each criterion the rule cites, one W3C "
          "names (a W3C failure technique, or an ACT rule W3C's Working "
          "Group approved)",
    "heuristic": "a FAIL is a probable failure of the criteria the rule "
                 "cites: markup alone cannot settle it, or W3C does not "
                 "itself name it",
    "policy": "never a FAIL: stricter than WCAG 2.1 AA (a pled pattern, or "
              "a WCAG 2.2 criterion), reported for review",
    "best-practice": "never a FAIL: WCAG does not require it on its own "
                     "(the notes say why), reported for review",
    "review": "never a FAIL: the rule only asks for review",
}
LAYER = {"static-dom": "on the markup", "rendered": "in the browser",
         "interaction": "interaction layer (not built)",
         "interaction+judge": "interaction layer and judge (not built)",
         "judge": "judge (not in 1.0)"}


def _text(value) -> str:
    """Prose for Markdown: `<`, `>` and `&` escaped, so a tag named in a
    sentence (\"a <title> as its first child\") reads as text and does not
    become one in a Markdown viewer (R3B-6). Code examples are fenced."""
    import html
    return html.escape(str(value or ""), quote=False)


def _checked(r: dict) -> str:
    if r.get("engine") == "axe-core":
        return f"axe-core's `{r.get('axe_rule')}`, in the browser"
    return "Bellbriar, " + LAYER.get(r.get("layer"), r.get("layer") or "")


def _fence(lang: str, text: str) -> str:
    return f"```{lang}\n{text}\n```"


def render(rulebook: dict) -> str:
    rules = rulebook["rules"]
    runs = [r for r in rules if r.get("status") == "implemented"
            and r.get("layer") in ("static-dom", "rendered")]
    other = [r for r in rules if r not in runs]
    out = [
        "# Rules reference",
        "",
        "Generated by `tools/make_rules_reference.py` from the rulebook "
        f"(`rulebook.json`, version {rulebook.get('rulebook_version')}, "
        f"SHA-256 `{rulebook_digest(rulebook)}`) and the fix guidance "
        "(`guidance.py`); the test suite fails when this file is out of "
        "date. Do not edit it by hand.",
        "",
        f"The rulebook holds {len(rules)} rules: {len(runs)} run today "
        f"({sum(1 for r in runs if r['layer'] == 'static-dom')} on the "
        f"markup, {sum(1 for r in runs if r['layer'] == 'rendered')} in "
        f"the browser), and {len(other)} are not in 1.0 (planned for the "
        "browser layers, or judged). A rule's verdict basis says what a "
        "finding from it means: only FAILs count against \"Tier-1 "
        "clean\" and the score, and against the gate, which with "
        "`--strict` also counts the reviews marked \"pled in "
        "complaints\" or \"a best practice\" (docs/METHODOLOGY.md, and "
        "the guide's \"Which fails are violations\"). The HTML report "
        "shows each rule's guidance beside its findings. The test suite "
        "runs the HTML examples below: each \"before\" example is found "
        "by its rule, failing if the rule can fail; each \"after\" one "
        "fails no rule and is not found by its own, except where a rule "
        "always asks a person (a captioned video is still asked about "
        "audio description); other rules may still list it for review.",
        "",
        "| Rule | Name | WCAG | Tier | Basis | Checked by |",
        "|---|---|---|---|---|---|",
    ]
    for r in runs:
        out.append(f"| [`{r['id']}`](#{r['id']}) | {_text(r['name'])} | "
                   f"{', '.join(r.get('sc') or []) or '—'} | {r['tier']} | "
                   f"{r.get('verdict_basis')} | {_checked(r)} |")
    out += ["", "## Rules that run", ""]
    for r in runs:
        g = guidance_for(r["id"])
        out.append(f"### {r['id']}")
        out.append("")
        out.append(f"**{_text(r['name'])}.** "
                   + (f"WCAG {', '.join(r['sc'])}" if r.get("sc")
                      else "Cites no WCAG criterion")
                   + (f" ([Understanding]({r['understanding']}))"
                      if r.get("understanding") else "")
                   + f" · Tier {r['tier']} · checked by {_checked(r)} · "
                   f"basis `{r.get('verdict_basis')}`: "
                   f"{BASIS.get(r.get('verdict_basis'), '')}.")
        out.append("")
        acts = r.get("act_rules") or []
        if acts:
            out.append("W3C ACT rules: " + "; ".join(
                f"[{a['id']}](https://www.w3.org/WAI/standards-guidelines/"
                f"act/rules/{a['id']}/) {_text(a['title'])} ({a['status']})"
                for a in acts) + ".")
            out.append("")
        if r.get("w3c_failures"):
            out.append("W3C failure techniques: "
                       + ", ".join(r["w3c_failures"]) + ".")
            out.append("")
        if r.get("notes"):
            out.append(_text(r["notes"]))
            out.append("")
        if g:
            out.append(f"**Why it matters.** {_text(g['why'])}")
            out.append("")
            out.append(f"**How to fix it.** {_text(g['fix'])}")
            out.append("")
            out.append("HTML, before:")
            out.append("")
            out.append(_fence("html", g["html_bad"]))
            out.append("")
            out.append("HTML, after:")
            out.append("")
            out.append(_fence("html", g["html_good"]))
            out.append("")
            out.append("React:")
            out.append("")
            out.append(_fence("jsx", g["react"]))
            out.append("")
            out.append("Vue:")
            out.append("")
            out.append(_fence("vue", g["vue"]))
            out.append("")
    out += ["## Rules not in 1.0", "",
            "Specified, with their tier and criteria, for the layers "
            "1.0 does not run: the interaction layer and the browser "
            "checks not built yet, and the judged rules (adequacy of alt "
            "text, link purpose, headings), which need a calibrated judge "
            "(docs/ROADMAP.md). A run reports them as not evaluated, never "
            "as passed.", "",
            "| Rule | Name | WCAG | Tier | Layer | Status |",
            "|---|---|---|---|---|---|"]
    for r in other:
        status = ("not in 1.0" if r.get("status") == "implemented"
                  else r.get("status"))
        out.append(f"| `{r['id']}` | {_text(r['name'])} | "
                   f"{', '.join(r.get('sc') or []) or '—'} | {r['tier']} | "
                   f"{r.get('layer')} | {status} |")
    out.append("")
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if docs/RULES.md is not what this writes")
    args = ap.parse_args(argv)
    text = render(load_rulebook())
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/RULES.md is out of date: run "
                  "python tools/make_rules_reference.py", file=sys.stderr)
            return 1
        print("docs/RULES.md is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
